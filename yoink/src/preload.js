'use strict';
const { contextBridge, ipcRenderer } = require('electron');
const inv = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);
contextBridge.exposeInMainWorld('yoink', {
  meta: inv('meta'),
  getSettings: inv('settings:get'),
  setSettings: inv('settings:set'),
  chooseFolder: inv('settings:chooseFolder'),
  info: inv('info'),
  updateYtdlp: inv('ytdlp:update'),
  openClipsFolder: inv('clips:open'),
  openUrl: inv('open:url'),
  openDownloadPage: inv('update:open'),
  checkForUpdates: inv('update:check'),
  installUpdate: inv('update:install'),
  cancelUpdate: inv('update:cancel'),
  skipUpdate: inv('update:skip'),
  syncStatus: inv('sync:status'),
  signIn: inv('sync:signin'),
  signOut: inv('sync:signout'),
  syncNow: inv('sync:now'),
  favSetTags: inv('fav:setTags'),
  cleanStart: inv('clean:start'),
  cleanCancel: inv('clean:cancel'),
  cleanStatus: inv('clean:status'),
  cleanRemove: inv('clean:remove'),
  detectKey: inv('clip:key'),
  saveClip: inv('clip:save'),
  search: inv('search'),
  loadMore: inv('search:more'),
  cancel: inv('search:cancel'),
  retrim: inv('clip:retrim'),
  favList: inv('fav:list'),
  favUpdate: inv('fav:update'),
  favToggle: inv('fav:toggle'),
  historyList: inv('history:list'),
  historyRemove: inv('history:remove'),
  historyClear: inv('history:clear'),
  cacheInfo: inv('cache:info'),
  cacheClear: inv('cache:clear'),
  startDrag: (f) => ipcRenderer.send('drag:start', f),
  onUpdate: (cb) => ipcRenderer.on('update:event', (_e, evt) => cb(evt)),
  onClean: (cb) => ipcRenderer.on('clean:event', (_e, evt) => cb(evt)),
  onFav: (cb) => ipcRenderer.on('fav:event', (_e, evt) => cb(evt)),
  onSync: (cb) => ipcRenderer.on('sync:event', (_e, evt) => cb(evt)),
  onEvent: (cb) => ipcRenderer.on('yoink:event', (_e, evt) => cb(evt)),
});
